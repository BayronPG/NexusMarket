package com.nexusmarket.application.service;

import com.nexusmarket.application.context.ActorContext;
import com.nexusmarket.application.error.AuthorizationException;
import com.nexusmarket.application.error.NotFoundException;
import com.nexusmarket.application.port.in.ManageRefundsUseCase;
import com.nexusmarket.application.port.out.BuyerRepository;
import com.nexusmarket.application.port.out.OrderRepository;
import com.nexusmarket.application.port.out.RefundRepository;
import com.nexusmarket.application.query.PageQuery;
import com.nexusmarket.application.query.PageResult;
import com.nexusmarket.application.support.Authorization;
import com.nexusmarket.application.support.Validation;
import com.nexusmarket.domain.buyer.Buyer;
import com.nexusmarket.domain.order.Order;
import com.nexusmarket.domain.returns.Refund;
import com.nexusmarket.domain.user.Role;
import org.springframework.stereotype.Service;

/**
 * Application service that exposes the refunds generated by received returns.
 *
 * <p>Increment "envío y devolución por ítem" (2026-11-10): refunds are no longer
 * requested directly. A received return creates one partial refund with the
 * historical unit price, and this service only reads them.</p>
 *
 * <p>Traceability: OBJ-11, RG-03.</p>
 */
@Service
public class RefundService implements ManageRefundsUseCase {

    private final RefundRepository refundRepository;
    private final OrderRepository orderRepository;
    private final BuyerRepository buyerRepository;

    public RefundService(RefundRepository refundRepository,
                         OrderRepository orderRepository,
                         BuyerRepository buyerRepository) {
        this.refundRepository = refundRepository;
        this.orderRepository = orderRepository;
        this.buyerRepository = buyerRepository;
    }

    @Override
    public Refund findRefund(ActorContext actor, Long refundId) {
        Authorization.requireAnyRole(actor, Role.BUYER, Role.ADMINISTRATOR);
        Validation.requireNotNull(refundId, "refundId");
        Refund refund = refundRepository.findById(refundId)
                .orElseThrow(() -> new NotFoundException("Refund not found: " + refundId));
        requireOrderAccess(actor, refund.getOrderId());
        return refund;
    }

    @Override
    public PageResult<Refund> findRefundsByOrder(ActorContext actor, Long orderId, PageQuery query) {
        Authorization.requireAnyRole(actor, Role.BUYER, Role.ADMINISTRATOR);
        Validation.requireNotNull(orderId, "orderId");
        requireOrderAccess(actor, orderId);
        return refundRepository.findByOrderId(orderId, query);
    }

    private void requireOrderAccess(ActorContext actor, Long orderId) {
        if (actor.role() == Role.ADMINISTRATOR) {
            return;
        }
        Order order = orderRepository.findById(orderId)
                .orElseThrow(() -> new NotFoundException("Order not found: " + orderId));
        Buyer buyer = buyerRepository.findByUserId(actor.userId())
                .orElseThrow(() -> new NotFoundException(
                        "Buyer not found for the authenticated user"));
        if (!buyer.getId().equals(order.getBuyerId())) {
            throw new AuthorizationException("A buyer can only read its own refunds (RG-03)");
        }
    }
}
