package com.nexusmarket.infrastructure.web.controller;

import com.nexusmarket.application.context.ActorContext;
import com.nexusmarket.application.port.in.ManageRefundsUseCase;
import com.nexusmarket.application.query.PageQuery;
import com.nexusmarket.infrastructure.web.SortWhitelist;
import com.nexusmarket.infrastructure.web.dto.PageResponse;
import com.nexusmarket.infrastructure.web.dto.RefundResponse;
import com.nexusmarket.infrastructure.web.mapper.RefundWebMapper;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.Parameter;
import io.swagger.v3.oas.annotations.responses.ApiResponse;
import io.swagger.v3.oas.annotations.responses.ApiResponses;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.constraints.Max;
import jakarta.validation.constraints.Min;
import jakarta.validation.constraints.Pattern;
import java.util.Set;
import org.springframework.validation.annotation.Validated;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.RestController;

/**
 * REST adapter for reading the partial refunds generated by returns.
 *
 * <p>Increment "envío y devolución por ítem" (2026-11-10): the refund is created
 * automatically when the return is received, so this controller only exposes
 * GET operations.</p>
 *
 * <p>Traceability: OBJ-11.</p>
 */
@RestController
@RequestMapping("/api/refunds")
@Tag(name = "Refunds", description = "Reembolsos parciales por devolucion (OBJ-11)")
@Validated
public class RefundController {

    private static final Set<String> SORT_FIELDS =
            Set.of("id", "returnId", "orderId", "orderItemId", "amount", "createdAt");

    private final ManageRefundsUseCase manageRefundsUseCase;

    public RefundController(ManageRefundsUseCase manageRefundsUseCase) {
        this.manageRefundsUseCase = manageRefundsUseCase;
    }

    @GetMapping("/{refundId}")
    @Operation(summary = "Consulta un reembolso parcial")
    @ApiResponses({
            @ApiResponse(responseCode = "401", description = "Token ausente o invalido"),
            @ApiResponse(responseCode = "200", description = "Reembolso encontrado"),
            @ApiResponse(responseCode = "403", description = "Solo el comprador dueno o el administrador"),
            @ApiResponse(responseCode = "404", description = "Reembolso inexistente")})
    public RefundResponse find(@Parameter(hidden = true) ActorContext actor,
                               @PathVariable Long refundId) {
        return RefundWebMapper.toResponse(manageRefundsUseCase.findRefund(actor, refundId));
    }

    @GetMapping
    @Operation(summary = "Lista los reembolsos de un pedido")
    @ApiResponses({
            @ApiResponse(responseCode = "401", description = "Token ausente o invalido"),
            @ApiResponse(responseCode = "200", description = "Reembolsos del pedido"),
            @ApiResponse(responseCode = "403", description = "Solo el comprador dueno o el administrador"),
            @ApiResponse(responseCode = "404", description = "Pedido inexistente")})
    public PageResponse<RefundResponse> findByOrder(
            @Parameter(hidden = true) ActorContext actor,
            @RequestParam Long orderId,
            @RequestParam(defaultValue = "0") @Min(0) int page,
            @RequestParam(defaultValue = "20") @Min(1) @Max(100) int size,
            @RequestParam(defaultValue = "id,asc")
            @Pattern(regexp = "[A-Za-z][A-Za-z0-9]*(,(?i:asc|desc))?") String sort) {
        SortWhitelist.require(sort, SORT_FIELDS);
        return PageResponse.from(
                manageRefundsUseCase.findRefundsByOrder(actor, orderId,
                        PageQuery.of(page, size, sort)),
                RefundWebMapper::toResponse);
    }
}
