package com.nexusmarket.domain.returns;

import java.time.LocalDateTime;

/**
 * Return of one line of an order.
 *
 * <p>Increment "envío y devolución por ítem" (2026-11-10): a buyer returns a
 * quantity of a delivered line; the administrator approves it and the
 * logistics operator receives it. A received RESELLABLE return restores the
 * available stock, a DAMAGED one increases the damaged quantity.</p>
 *
 * <p>Business rules: only a DELIVERED line can be returned; the quantity is
 * positive and never exceeds the purchased quantity minus previous returns;
 * reception is idempotent so stock is never restored twice.</p>
 *
 * <p>Traceability: OBJ-11, RN-12.</p>
 */
public class Return {

    private Long id;

    /** Order that contains the returned line. */
    private Long orderId;

    /** Returned order line. */
    private Long orderItemId;

    /** Buyer that owns the order; only the owner requests returns (RG-03). */
    private Long buyerId;

    /** Returned units; positive. */
    private int quantity;

    /** Motive declared by the buyer. */
    private String reason;

    /** Physical condition of the returned units. */
    private ReturnCondition condition;

    /** Current lifecycle state. */
    private ReturnStatus status;

    /** Creation timestamp. */
    private LocalDateTime createdAt;

    /** Reception timestamp; null until the return is received. */
    private LocalDateTime receivedAt;

    /** Refund generated by this return; derived on read, not persisted. */
    private Long refundId;

    public Return() {
    }

    public Return(Long id, Long orderId, Long orderItemId, Long buyerId, int quantity,
                  String reason, ReturnCondition condition, ReturnStatus status,
                  LocalDateTime createdAt, LocalDateTime receivedAt) {
        this.id = id;
        this.orderId = orderId;
        this.orderItemId = orderItemId;
        this.buyerId = buyerId;
        setQuantity(quantity);
        this.reason = reason;
        this.condition = condition;
        this.status = status;
        this.createdAt = createdAt;
        this.receivedAt = receivedAt;
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public Long getOrderId() {
        return orderId;
    }

    public void setOrderId(Long orderId) {
        this.orderId = orderId;
    }

    public Long getOrderItemId() {
        return orderItemId;
    }

    public void setOrderItemId(Long orderItemId) {
        this.orderItemId = orderItemId;
    }

    public Long getBuyerId() {
        return buyerId;
    }

    public void setBuyerId(Long buyerId) {
        this.buyerId = buyerId;
    }

    public int getQuantity() {
        return quantity;
    }

    /**
     * Sets the returned quantity; it must be positive.
     *
     * @param quantity returned units
     * @throws IllegalArgumentException if the quantity is not positive
     */
    public void setQuantity(int quantity) {
        if (quantity <= 0) {
            throw new IllegalArgumentException("The returned quantity must be positive");
        }
        this.quantity = quantity;
    }

    public String getReason() {
        return reason;
    }

    public void setReason(String reason) {
        this.reason = reason;
    }

    public ReturnCondition getCondition() {
        return condition;
    }

    public void setCondition(ReturnCondition condition) {
        this.condition = condition;
    }

    public ReturnStatus getStatus() {
        return status;
    }

    public void setStatus(ReturnStatus status) {
        this.status = status;
    }

    public LocalDateTime getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(LocalDateTime createdAt) {
        this.createdAt = createdAt;
    }

    public LocalDateTime getReceivedAt() {
        return receivedAt;
    }

    public void setReceivedAt(LocalDateTime receivedAt) {
        this.receivedAt = receivedAt;
    }

    /** Refund generated by this return; derived on read, not persisted. */
    public Long getRefundId() {
        return refundId;
    }

    public void setRefundId(Long refundId) {
        this.refundId = refundId;
    }

    /** Whether the units were physically received. */
    public boolean isReceived() {
        return status == ReturnStatus.RECEIVED;
    }

    /**
     * Approves a requested return.
     *
     * @throws IllegalStateException if the return is not REQUESTED
     */
    public void approve() {
        if (status != ReturnStatus.REQUESTED) {
            throw new IllegalStateException("Only a requested return can be approved");
        }
        this.status = ReturnStatus.APPROVED;
    }

    /**
     * Marks the return as received and stamps the reception time.
     *
     * @throws IllegalStateException if the return is not APPROVED
     */
    public void receive() {
        if (status != ReturnStatus.APPROVED) {
            throw new IllegalStateException("Only an approved return can be received");
        }
        this.status = ReturnStatus.RECEIVED;
        this.receivedAt = LocalDateTime.now();
    }
}
